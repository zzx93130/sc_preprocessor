"""Self-contained reproducibility script archived with every sample.

Records exact tool versions, reference, command lines, repo commit and the
SRR->GSM mapping; running it on a machine with the same tools regenerates the
results from the archived FASTQs.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import time
from pathlib import Path

_VERSIONS_CACHE = {}


def tool_versions(ctx) -> dict:
    key = id(ctx.runner)
    if key not in _VERSIONS_CACHE:
        _VERSIONS_CACHE[key] = ctx.runner.versions()
    return _VERSIONS_CACHE[key]


def repo_commit(root: Path) -> str:
    try:
        r = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                           capture_output=True, text=True, timeout=10)
        if r.returncode == 0:
            return r.stdout.strip()
    except Exception:  # noqa: BLE001
        pass
    return "unknown"


def _py_packages() -> str:
    try:
        r = subprocess.run(["python3", "-m", "pip", "freeze"],
                           capture_output=True, text=True, timeout=60)
        return r.stdout.strip()
    except Exception:  # noqa: BLE001
        return ""


def write_repro(ctx, repro_dir: Path, fastq_zip_sha: str):
    repro_dir.mkdir(parents=True, exist_ok=True)
    cfg = ctx.cfg
    s = ctx.sample
    versions = tool_versions(ctx)
    cc = cfg.data["concurrency"]
    ref = cfg.path("reference_dir")
    ref_json = ""
    if (ref / "reference.json").is_file():
        ref_json = (ref / "reference.json").read_text()

    meta = {
        "sample": ctx.sid,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "mode": s["mode"],
        "srr_to_sample": {srr: ctx.sid for srr in s["srrs"]},
        "sample_meta": s["meta"],
        "repo": "https://github.com/zzx93130/sc_preprocessor.git",
        "repo_commit": repo_commit(cfg.root),
        "reference_dir": str(ref),
        "reference_json": ref_json,
        "cellranger_dir": str(cfg.path("cellranger_dir")),
        "tool_versions": versions,
        "python_packages": _py_packages(),
        "config": cfg.data,
        "fastq_zip_sha256": fastq_zip_sha,
    }
    meta_path = repro_dir / "versions.json"
    meta_path.write_text(json.dumps(meta, indent=1))

    cores = cc["cellranger_cores"]
    mem = cc["cellranger_mem_gb"]
    create_bam = "true" if cfg.get("pipeline", "create_bam", default=True) else "false"
    cr_platform = cfg.get("docker", "cellranger_platform")
    cr_image = cfg.get("docker", "cellranger_image")
    vc_image = cfg.get("docker", "velocyto_image")
    vc_platform = cfg.get("docker", "velocyto_platform") or ""
    vc_platform_flag = f"--platform {vc_platform} " if vc_platform else ""
    threads = cc.get("convert_threads", 6)
    cr_mount = cfg.get(
        "docker", "cellranger_volume", default=""
    ) or str(cfg.path("cellranger_dir"))
    paired = s["meta"].get("paired_input_decision")
    paired_setup = 'ANALYSIS_FASTQ="$WORKDIR/fastq"'
    paired_script = None
    if paired:
        paired_script = repro_dir / "paired_input.py"
        shutil.copy2(Path(__file__).with_name("paired_input.py"), paired_script)
        lane_json = json.dumps(paired["lanes"])
        paired_setup += ('\npython3 "$HERE/paired_input.py" --source "$WORKDIR/fastq" '
                         '--destination "$WORKDIR/cellranger_fastq" --sample "$SAMPLE" '
                         f"--lanes-json '{lane_json}'\n"
                         'ANALYSIS_FASTQ="$WORKDIR/cellranger_fastq"')

    script = f"""#!/usr/bin/env bash
# Reproduce sample {ctx.sid} from its archived FASTQs.
# Generated by scpre on {meta['generated_at']}
#
#   repo:        {meta['repo']}  @ {meta['repo_commit']}
#   cellranger:  {versions.get('cellranger', '?')}
#   sra-tools:   {versions.get('sra-tools', '?')}
#   velocyto:    {versions.get('velocyto', '?')}
#   reference:   {ref}
#   SRR -> sample: {json.dumps(meta['srr_to_sample'])}
#   fastq zip sha256: {fastq_zip_sha}
#
# Requirements: bash, unzip, Docker (with x86_64 emulation on Apple Silicon),
# the Cell Ranger bundle and reference at the paths below (edit to relocate).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SAMPLE="{ctx.sid}"
CELLRANGER_SOURCE="{cr_mount}"
REFERENCE_DIR="{ref}"
WORKDIR="${{1:-$HERE/../rerun}}"
FASTQ_ZIP="$HERE/../archives/$SAMPLE.fastq.zip"

echo ">> verifying archived FASTQ zip"
echo "{fastq_zip_sha}  $FASTQ_ZIP" | shasum -a 256 -c - || \\
  echo "WARNING: checksum mismatch — archive may have changed"

mkdir -p "$WORKDIR/fastq" "$WORKDIR/cellranger" "$WORKDIR/loom" "$WORKDIR/tmp"
echo ">> extracting FASTQs"
unzip -n "$FASTQ_ZIP" -d "$WORKDIR/fastq"
{paired_setup}

echo ">> cellranger count"
docker run --rm --init --platform {cr_platform} \\
  -v "$CELLRANGER_SOURCE":/opt/cellranger:ro \\
  -v "$REFERENCE_DIR":/ref:ro \\
  -v "$ANALYSIS_FASTQ":/fastq:ro \\
  -v "$WORKDIR/cellranger":/work \\
  -w /work -e TMPDIR=/work/tmp {cr_image} \\
  /opt/cellranger/cellranger count \\
    --id="$SAMPLE" --fastqs=/fastq --sample="$SAMPLE" \\
    --transcriptome=/ref \\
    --localcores={cores} --localmem={mem} \\
    --create-bam={create_bam} --disable-ui

echo ">> velocyto loom"
GTF="$REFERENCE_DIR/genes/genes.gtf"
if [ ! -f "$GTF" ]; then
  GTF="$WORKDIR/genes.gtf"
  gunzip -c "$REFERENCE_DIR/genes/genes.gtf.gz" > "$GTF"
fi
docker run --rm --init {vc_platform_flag}\\
  -v "$WORKDIR/cellranger/$SAMPLE/outs":/outs:ro \\
  -v "$(dirname "$GTF")":/gtf:ro \\
  -v "$WORKDIR/loom":/loom {vc_image} \\
  velocyto run \\
    -b /outs/filtered_feature_bc_matrix/barcodes.tsv.gz \\
    -o /loom -e "$SAMPLE" -@ {threads} \\
    /outs/possorted_genome_bam.bam "/gtf/$(basename "$GTF")"

echo ">> done: $WORKDIR/cellranger/$SAMPLE/outs and $WORKDIR/loom/$SAMPLE.loom"
"""
    script_path = repro_dir / f"reproduce_{ctx.sid}.sh"
    script_path.write_text(script)
    script_path.chmod(0o755)

    # copy the exact pipeline code used (small, self-contained)
    code_note = repro_dir / "PIPELINE_CODE.txt"
    code_note.write_text(
        f"Pipeline code: {meta['repo']} @ commit {meta['repo_commit']}\n"
        f"(pipeline/ directory of the repo; config snapshot in versions.json)\n")
    return [script_path, meta_path, code_note] + ([paired_script] if paired_script else [])
